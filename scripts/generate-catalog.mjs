// Renders the tool catalogue of the connector from docs/catalog.source.json, which the product repo produces
// (scripts/export-public-mcp-catalog.ts). Nothing here is typed by hand: to change the list, change the product
// catalogue, export again and run this script.
//   node scripts/generate-catalog.mjs [path/to/catalog.source.json]   writes docs/tools.md and docs/tools.json
//   node scripts/generate-catalog.mjs --check                          exits 1 when the committed files are stale
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const check = args.includes('--check');
const sourcePath = args.find((arg) => !arg.startsWith('--')) ?? join(root, 'docs/catalog.source.json');
const source = JSON.parse(readFileSync(sourcePath, 'utf8'));

const cell = (text) => String(text).replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const lines = [
  '# Herramientas del conector / Connector tools',
  '',
  `<!-- Generated by scripts/generate-catalog.mjs from docs/catalog.source.json (${cell(source.source)}). Do not edit by hand. -->`,
  '',
  `**${source.toolCount} herramientas / tools.** Cada una pide un permiso concreto (\`scope\`). / Each one asks for a specific permission.`,
  '',
];
for (const group of source.areas) {
  lines.push(`## ${group.area}`, '', `Permiso / Scope: \`${group.scope}\``, '', '| Herramienta / Tool | Qué hace |', '| --- | --- |');
  for (const tool of group.tools) lines.push(`| \`${tool.name}\` | **${cell(tool.label)}.** ${cell(tool.desc)} |`);
  lines.push('');
}
const markdown = `${lines.join('\n').trimEnd()}\n`;
const json = `${JSON.stringify(
  { source: source.source, toolCount: source.toolCount, areas: source.areas },
  null,
  2,
)}\n`;

const outputs = { 'docs/tools.md': markdown, 'docs/tools.json': json };
let stale = false;
for (const [file, text] of Object.entries(outputs)) {
  const target = join(root, file);
  if (check) {
    let current = '';
    try {
      current = readFileSync(target, 'utf8');
    } catch {
      // missing counts as stale
    }
    if (current !== text) {
      console.error(`${file} is stale: run "npm run catalog"`);
      stale = true;
    }
  } else writeFileSync(target, text);
}
if (stale) process.exit(1);
